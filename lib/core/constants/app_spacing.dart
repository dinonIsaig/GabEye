class AppSpacing {
  AppSpacing._();

  /// Spacing between distinct sections on a page (e.g. Help & Feedback, Settings).
  static const double sectionSpacing = 32.0;

  /// Spacing between items/cards within a section.
  static const double itemSpacing = 16.0;

  /// Compact vertical spacing for related sub-elements.
  static const double compactSpacing = 12.0;

  /// Small micro-spacing (e.g., between title and subtitle).
  static const double smallSpacing = 8.0;

  /// Extra small spacing (e.g., between icon and text).
  static const double tinySpacing = 4.0;
}
